; 01-exit.asm - най-малката програма, която може да се изпълни.
;
; Не прави нищо, освен да приключи с изходен код 42.
;
;   make 01-exit
;   ./01-exit
;   echo $?                     # 42
;
; Опит: изтрийте реда със syscall и стартирайте отново. Какво се случва?

section .text
    global _start               ; етикетът _start се вижда и извън файла - за ld

_start:                         ; оттук започва изпълнението на програмата
    mov rax, 60                 ; номер на системното извикване exit
    mov rdi, 42                 ; първи аргумент - изходният код
    syscall                     ; предаваме управлението на ядрото
