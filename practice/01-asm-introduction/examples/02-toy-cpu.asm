; 02-toy-cpu.asm - програмата от схемата на процесора, но на x86-64.
;
; В паметта на схемата има:
;
;   адрес  0: 0010 1110   LOAD_A 14    A = RAM[14]
;   адрес  1: 0001 1111   LOAD_B 15    B = RAM[15]
;   адрес  2: 1000 0100   ADD B, A     A = B + A
;   адрес  3: 0100 1101   STORE_A 13   RAM[13] = A
;   адрес 14: 0000 0011   3
;   адрес 15: 0000 1110   14
;
; Тук регистър A е rax, а B - rbx. Вместо адреси 13, 14 и 15 пишем етикети -
; конкретните адреси избират асемблерът и свързващият редактор.
;
;   make 02-toy-cpu
;   ./02-toy-cpu
;   echo $?                                 # 17
;   objdump -d -M intel 02-toy-cpu          # машинният код на инструкциите

default rel                     ; адресите в [] се смятат спрямо rip - това е
                                ;   препоръчителното в 64-битов режим

section .data
    result  dq 0                ; „адрес 13“
    x       dq 3                ; „адрес 14“
    y       dq 14               ; „адрес 15“

section .text
    global _start

_start:
    mov rax, [x]                ; LOAD_A 14:  rax = стойността на адрес x
    mov rbx, [y]                ; LOAD_B 15:  rbx = стойността на адрес y
    add rax, rbx                ; ADD B, A:   rax = rax + rbx
                                ;   (в схемата резултатът отива във втория
                                ;   регистър, в NASM - в първия операнд)
    mov [result], rax           ; STORE_A 13: стойността на адрес result = rax

    ; Схемата спира дотук. Истинската програма трябва да поиска от ядрото да
    ; я приключи - иначе процесорът продължава със следващите байтове.
    mov rdi, [result]           ; изходен код - резултатът
    mov rax, 60                 ; exit
    syscall
